"""
بنك التمارين لبرنامج تأهيل عضلات الرقبة للاعبي الفنون القتالية.

كل تمرين قاموس بالحقول:
id, name, category, tags, levels (1..4), phase (warmup|main|cooldown), resisted, external
(مقاومة خارجية: مطاط/جهاز/شريك)، unilateral, equipment, tempo_s, hold_s, instructions,
common_errors, contraindications, وحقول اختيارية:
  cam          مواصفات التتبع بالكاميرا (ml/live_coach.ExerciseCoach)
  dose         جرعة ثابتة {'sets','reps','hold_s'} للإطالات/الاسترخاء/التثقيف
  rep_scale    معامل تقليل التكرارات (للإيزومتري)
  max_pct      سقف شدة المقاومة % من MVC لهذا التمرين
  sports       قائمة جذور أسماء الرياضات المناسبة (None = لكل الرياضات)

تنبيه: التمارين مقترحة وتخضع لموافقة الأخصائي/المشرف قبل التطبيق. لا يتضمن البنك
«جسر الرقبة الكامل» (neck bridge) ولا أي تمرين بحمل محوري ثقيل على الرقبة.
"""


def _cam(mode, axis, sign, view, rom_key, min_rep_s, default_target, safe_extra, hold_s=None):
    d = {"mode": mode, "axis": axis, "sign": sign, "view": view, "rom_key": rom_key,
         "min_rep_s": float(min_rep_s), "default_target": float(default_target),
         "safe_extra": float(safe_extra)}
    if hold_s is not None:
        d["hold_s"] = float(hold_s)
    return d


def _ex(id, name, category, tags, levels, phase, instructions, common_errors, contra="",
        resisted=False, external=False, unilateral=False, equipment="بدون معدات",
        tempo_s=3.0, hold_s=None, cam=None, dose=None, rep_scale=None, max_pct=None, sports=None):
    d = dict(id=id, name=name, category=category, tags=list(tags), levels=list(levels), phase=phase,
             resisted=resisted, external=external, unilateral=unilateral, equipment=equipment,
             tempo_s=float(tempo_s), hold_s=hold_s, instructions=list(instructions),
             common_errors=list(common_errors), contraindications=contra or "لا يوجد خاص — راجع الاحتياطات العامة للبرنامج.")
    if cam:
        d["cam"] = cam
    if dose:
        d["dose"] = dose
    if rep_scale:
        d["rep_scale"] = rep_scale
    if max_pct is not None:
        d["max_pct"] = max_pct
    if sports:
        d["sports"] = sports
    return d


